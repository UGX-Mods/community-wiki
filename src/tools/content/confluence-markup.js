/**
 * Leftovers of the Confluence import that Wiki.js does not use: wrapper divs,
 * Confluence / Jira classes, macro data attributes and inline styles without
 * a visible effect. Styles that change the look (colors, alignment, indents)
 * are kept.
 */
import fs from 'node:fs';
import { encoding, readPage } from '../lib/pages.js';
import { HTMLParser, formatHtml, parseHtmlContent } from '../lib/html.js';

/** wrappers which are replaced by their content */
const UNWRAP_SELECTORS = [
  'div.table-wrap',
  'div.plugin-tabmeta-details',
  'span.static-jira-issues_count',
  'span.nolink',
  'span.mw-headline',
  'span.inline-comment-marker',
];

/** classes of Confluence / Jira macros, not styled by the theme */
const CONFLUENCE_CLASSES = [
  'confluenceTable',
  'confluenceTh',
  'confluenceTd',
  'wrapped',
  'confluence-link',
  'external-link',
  'issue-link',
  'content-type-page',
  'refresh-module-id',
  'refresh-issues-bottom',
  'jira-table',
  'jira-issues',
  'total-issues-count',
  'metadata-summary-macro',
  'sorter-text',
  'status-macro',
  'inline-task-list',
  'fancy_list',
  'arrow_list',
  'details',
  'summary',
  'null',
];

/** ids generated by Confluence macros */
const REGEX_MACRO_ID =
  /^(?:refresh-module-+\d+|jira-issues-+\d+|total-issues-count)$/;

/**
 * Inline style declarations without visible effect in Wiki.js (Confluence
 * defaults like the font size / line height, or no-ops like `text-decoration: none`)
 */
const REGEX_NOOP_STYLE =
  /^(?:text-decoration:\s*none|line-height:.*|font-size:\s*14px|white-space:\s*normal)$/i;

/**
 * @param {string} style
 * @param {string} tagName lower case tag name
 * @returns {string} remaining declarations
 */
function cleanStyle(style, tagName) {
  // a line break has nothing to style, colgroups get their width from the content
  if (tagName === 'br' || tagName === 'col') return '';
  return style
    .split(';')
    .map((d) => d.trim())
    .filter((d) => d && !REGEX_NOOP_STYLE.test(d))
    .join('; ');
}

/** a div only holding these can be removed without changing the layout */
const BLOCK_TAGS = new Set([
  'div',
  'table',
  'p',
  'ul',
  'ol',
  'pre',
  'h2',
  'h3',
]);

/**
 * @param {HTMLParser.HTMLElement} el
 */
function hasNoAttributes(el) {
  return Object.keys(el.attributes).length === 0;
}

/**
 * @param {HTMLParser.HTMLElement} el
 */
function unwrap(el) {
  el.replaceWith(...el.childNodes);
}

/**
 * @param {HTMLParser.Node} n
 */
function isBlank(n) {
  return (
    n.nodeType === HTMLParser.NodeType.TEXT_NODE &&
    // rawText: `&nbsp;` paragraphs are intended blank lines
    /^[ \t\r\n]*$/.test(n.rawText)
  );
}

/**
 * @param {HTMLParser.HTMLElement} root parsed page
 */
function cleanupAttributes(root) {
  for (const el of root.querySelectorAll('*')) {
    if (el.hasAttribute('style')) {
      const style = cleanStyle(el.getAttribute('style') ?? '', el.rawTagName);
      if (style) el.setAttribute('style', style);
      else el.removeAttribute('style');
    }

    for (const cl of CONFLUENCE_CLASSES) el.classList.remove(cl);
    if (el.rawTagName === 'td') el.classList.remove('title');
    if (el.hasAttribute('class') && el.classList.length === 0) {
      el.removeAttribute('class');
    }

    Object.keys(el.attributes)
      .filter((name) => name.startsWith('data-'))
      .forEach((name) => el.removeAttribute(name));
    if (REGEX_MACRO_ID.test(el.id)) el.removeAttribute('id');
  }
}

/**
 * @param {HTMLParser.HTMLElement} root parsed page
 */
function cleanupElements(root) {
  root.querySelectorAll(UNWRAP_SELECTORS.join(',')).forEach(unwrap);

  // spans without attributes left are pointless, as are divs around blocks
  root
    .querySelectorAll('span')
    .filter((el) => hasNoAttributes(el))
    .forEach(unwrap);
  root
    .querySelectorAll('div')
    .filter(
      (el) =>
        hasNoAttributes(el) &&
        el.childNodes.every((n) =>
          n instanceof HTMLParser.HTMLElement
            ? BLOCK_TAGS.has(n.rawTagName)
            : isBlank(n),
        ),
    )
    .forEach(unwrap);

  // empty rows, colgroups without widths, empty paragraphs and code blocks
  root
    .querySelectorAll('tr, p')
    .filter((el) => hasNoAttributes(el) && el.childNodes.every(isBlank))
    .forEach((el) => el.remove());
  root
    .querySelectorAll('colgroup')
    .filter((el) =>
      el.childNodes.every(
        (n) =>
          isBlank(n) ||
          (n instanceof HTMLParser.HTMLElement && hasNoAttributes(n)),
      ),
    )
    .forEach((el) => el.remove());
  root
    .querySelectorAll('pre')
    .filter(
      (el) =>
        !el.innerHTML
          .replace(/<[^>]*>/g, '')
          .replace(/&nbsp;/g, '')
          .trim(),
    )
    .forEach((el) => el.remove());
}

/**
 * @param {string} content page source
 * @param {string} filePath used for the prettier config
 * @returns {Promise<string|null>} cleaned page, null if nothing changed or the
 * page is not formatted (a rewrite would reformat unrelated parts)
 */
async function cleanupPageMarkup(content, filePath) {
  if (
    (await formatHtml(parseHtmlContent(content).toString(), filePath)) !==
    content
  ) {
    console.warn('⚠️ Skipped, not prettier formatted @', filePath);
    return null;
  }

  // stray "<" at the end of some imported changelogs
  const root = parseHtmlContent(content.replace(/\n<\n$/, '\n'));
  cleanupAttributes(root);
  cleanupElements(root);
  const result = await formatHtml(root.toString(), filePath);
  return result === content ? null : result;
}

/**
 * @param {string[]} files html pages
 * @returns {Promise<number>} errors
 */
async function cleanupConfluenceMarkup(files) {
  let pages = 0;
  for (const filePath of files) {
    const data = await readPage(filePath);
    if (!data) continue;

    const result = await cleanupPageMarkup(data, filePath);
    if (result === null) continue;

    await fs.promises.writeFile(filePath, result, encoding);
    pages++;
  }

  console.log('Cleaned the Confluence markup of', pages, 'pages 🧹');
  return 0;
}

export { cleanStyle, cleanupPageMarkup, cleanupConfluenceMarkup };
